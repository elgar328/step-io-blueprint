//! Universal export stage — emit `inferred/universal.toml`, the schema-faithful
//! input for the `step-io` `codegen` generator (the SchemaTarget::Universal
//! model). It is the faithful schema-union of the source AP schemas PLUS
//! per-entity **DERIVE facts** so codegen can mark derived/derivable (`*`) slots
//! without a hand-written mapping.
//!
//! Depends only on the shared substrate (`express`, `refgraph`,
//! `common`).
//!
//! DERIVE facts are emitted raw (the entity's own `DERIVE` statement targets);
//! the hard-vs-derivable interpretation (which needs complex-part knowledge)
//! happens in codegen. Each entry is `"super.attr"` for a `SELF\super.attr`
//! redeclaration or `"attr"` for a plain own-attr derive.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::Path;

use serde::{Deserialize, Serialize};

use crate::export::common::{redeclaration_has_signal, redeclaration_owner, schema_rank, ty_repr};
use crate::export::narrowing::{Judge, union_types, with_element};
use crate::export::refgraph;
use crate::express::{AttrSpec, AttrType, EntitySchema, Schema, SupertypeExpr};

const OUT: &str = "inferred/universal.toml";
const REPORT: &str = "inferred/narrowing_report.txt";

/// What became of each attribute redeclaration, for review.
#[derive(Default)]
struct NarrowingReport {
    /// Entity and aggregate narrowings newly written (union-safe).
    emitted: Vec<String>,
    /// Scalar/SELECT redeclarations written as before although some edition
    /// admits more (`union_safe = false`).
    kept_unsafe: Vec<String>,
    /// Entity and aggregate narrowings not written, with the reason.
    rejected: Vec<String>,
    /// Redeclarations to a defined type, enumeration or primitive that the
    /// signal rule does not write either; out of scope here.
    non_reference: Vec<String>,
    /// Attributes some edition admits more for than the written schema does.
    narrower_than_union: Vec<String>,
    /// Declared types widened to the union of editions.
    widened: Vec<String>,
    /// Declarations narrower than the union of editions left as they are.
    not_widened: Vec<String>,
    /// Attributes mandatory here that some edition declares OPTIONAL.
    optional_elsewhere: Vec<String>,
    /// Attributes some edition declares with other aggregates or bounds.
    aggregate_elsewhere: Vec<String>,
}

impl NarrowingReport {
    fn write(&self) -> Result<(), String> {
        let mut out = String::from(
            "# Generated by `universal_export`. Attribute redeclarations and the union of editions.\n",
        );
        for (title, lines) in [
            (
                "emitted (union-safe entity/aggregate narrowings)",
                &self.emitted,
            ),
            (
                "kept but not union-safe (scalar/SELECT redeclarations)",
                &self.kept_unsafe,
            ),
            ("rejected (not written)", &self.rejected),
            ("not written: not a reference", &self.non_reference),
            (
                "narrower than the union of editions",
                &self.narrower_than_union,
            ),
            ("widened declarations (union of editions)", &self.widened),
            ("declaration differs, not widened", &self.not_widened),
            (
                "optional in some edition, mandatory here",
                &self.optional_elsewhere,
            ),
            (
                "other aggregates or bounds in some edition",
                &self.aggregate_elsewhere,
            ),
        ] {
            out.push_str(&format!("\n## {title}: {}\n", lines.len()));
            for l in lines {
                out.push_str(l);
                out.push('\n');
            }
        }
        fs::create_dir_all("inferred").map_err(|e| e.to_string())?;
        fs::write(REPORT, out).map_err(|e| e.to_string())?;
        eprintln!(
            "wrote {REPORT}: {} emitted, {} kept not union-safe, {} rejected, {} non-reference, {} narrower than union, {} widened, {} not widened",
            self.emitted.len(),
            self.kept_unsafe.len(),
            self.rejected.len(),
            self.non_reference.len(),
            self.narrower_than_union.len(),
            self.widened.len(),
            self.not_widened.len()
        );
        Ok(())
    }
}

/// `name` and its supertypes in the written declarations, nearest first.
fn universal_ancestors<'a>(
    decls: &BTreeMap<&'a str, &'a EntitySchema>,
    name: &'a str,
) -> Vec<&'a str> {
    let mut out = Vec::new();
    let mut stack = vec![name];
    while let Some(n) = stack.pop() {
        if out.contains(&n) {
            continue;
        }
        out.push(n);
        if let Some(e) = decls.get(n) {
            for p in e.parents.iter().rev() {
                if let Some((k, _)) = decls.get_key_value(p.as_str()) {
                    stack.push(k);
                }
            }
        }
    }
    out
}
const FILE_CORPUS_USAGE: &str = "corpus_usage.toml";

/// Per-entity corpus usage record, deserialized from the frozen
/// `inferred/corpus_usage.toml` (produced externally by step-io-reference-check's
/// `corpus-usage` bin and copied in). Only `complex_part_count` is read here —
/// to recover real MI combinations the declaration-only rule misses; the file's
/// other columns are ignored on read.
#[derive(Debug, Clone, Deserialize)]
pub struct UsageRecord {
    /// Occurrences as a part of a complex MI instance (`#N=( ... NAME(...) ... )`).
    #[serde(default)]
    pub complex_part_count: usize,
}

/// Read the frozen corpus summary (`inferred/corpus_usage.toml`).
fn load_corpus_summary() -> Result<BTreeMap<String, UsageRecord>, String> {
    let path = Path::new("inferred").join(FILE_CORPUS_USAGE);
    if !path.exists() {
        return Err(format!(
            "{} not found — generate it with `cargo run --release --bin corpus-usage` \
             in step-io-reference-check and copy it into inferred/.",
            path.display()
        ));
    }
    let body = fs::read_to_string(&path).map_err(|e| format!("read {path:?}: {e}"))?;
    let mut outer: BTreeMap<String, BTreeMap<String, UsageRecord>> =
        toml::from_str(&body).map_err(|e| format!("parse {path:?}: {e}"))?;
    let summary = outer.remove("entity").unwrap_or_default();
    if summary.is_empty() {
        return Err(format!(
            "{} has no [entity.*] records — regenerate it.",
            path.display()
        ));
    }
    Ok(summary)
}

/// serde `skip_serializing_if` for a `false` bool (keep the file small).
fn is_false(b: &bool) -> bool {
    !*b
}

/// The entities `schema` lets share a complex record with another, as EXPRESS
/// reads its SUPERTYPE clauses: subtypes inside an ANDOR/AND combine;
/// subtypes a clause does not name are ANDORed with it, so they and every
/// subtype it names combine (a supertype with no clause names none); and the
/// subtypes of an entity that combines combine too.
fn combinable_in(schema: &Schema) -> BTreeSet<String> {
    let mut children: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    for (name, decl) in &schema.entities {
        for p in &decl.parents {
            children.entry(p.as_str()).or_default().push(name.as_str());
        }
    }
    let mut combinable = BTreeSet::new();
    for (name, decl) in &schema.entities {
        let mut named = BTreeSet::new();
        if let Some(expr) = &decl.supertype_expr {
            collect_combinable(expr, false, &mut combinable);
            collect_combinable(expr, true, &mut named);
        }
        let implicit: Vec<&str> = children
            .get(name.as_str())
            .into_iter()
            .flatten()
            .copied()
            .filter(|k| !named.contains(*k))
            .collect();
        if !implicit.is_empty() {
            combinable.extend(implicit.iter().map(|k| k.to_string()));
            combinable.extend(named);
        }
    }
    let mut stack: Vec<String> = combinable.iter().cloned().collect();
    while let Some(n) = stack.pop() {
        for k in children.get(n.as_str()).into_iter().flatten() {
            if combinable.insert(k.to_string()) {
                stack.push(k.to_string());
            }
        }
    }
    combinable
}

/// Collect entity names that appear inside an `AndOr`/`And` node (recursively).
/// These are the multiple-inheritance-combinable leaves — a top-level `OneOf`
/// (mutually exclusive subtypes, no ANDOR) is NOT combinable, so entities are
/// only collected once `in_andor` is set by entering an AndOr/And.
fn collect_combinable(expr: &SupertypeExpr, in_andor: bool, out: &mut BTreeSet<String>) {
    match expr {
        SupertypeExpr::Entity { name } => {
            if in_andor {
                out.insert(name.clone());
            }
        }
        SupertypeExpr::OneOf { children } => {
            for c in children {
                collect_combinable(c, in_andor, out);
            }
        }
        SupertypeExpr::AndOr { children } | SupertypeExpr::And { children } => {
            for c in children {
                collect_combinable(c, true, out);
            }
        }
    }
}

#[derive(Serialize)]
struct UnivAttr {
    name: String,
    ty: String,
    /// For a redeclaration, the entity that declares the attribute.
    #[serde(skip_serializing_if = "Option::is_none")]
    owner: Option<String>,
    /// For a redeclaration, whether every edition's type for the attribute
    /// falls inside it (`narrowing::Judge`), so reading may enforce it.
    #[serde(skip_serializing_if = "Option::is_none")]
    union_safe: Option<bool>,
}

/// One faithful entity declaration. Field order matters for toml: all
/// scalar/inline values (incl. the inline `derives` string array) precede the
/// `own_attrs`/`redeclared_attrs` array-of-tables.
#[derive(Serialize)]
struct UnivEntity {
    #[serde(skip_serializing_if = "Vec::is_empty")]
    parents: Vec<String>,
    is_abstract: bool,
    /// True if this entity can appear as a part of a Part21 complex (multiple-
    /// inheritance) record: it is an ANDOR/AND-combinable leaf or a transitive
    /// supertype of one. codegen gives it a part-bag variant (dual-appearance).
    #[serde(skip_serializing_if = "is_false")]
    is_complex_part: bool,
    #[serde(skip_serializing_if = "Vec::is_empty")]
    attr_conflicts: Vec<String>,
    /// Raw DERIVE targets: `"super.attr"` (SELF\super.attr) or `"attr"` (own).
    #[serde(skip_serializing_if = "Vec::is_empty")]
    derives: Vec<String>,
    /// Source AP schemas whose EXPRESS declares this entity, chronological
    /// (ap203e1 → ap242e3). Never empty. Membership data for coverage docs.
    schemas: Vec<String>,
    own_attrs: Vec<UnivAttr>,
    #[serde(skip_serializing_if = "Vec::is_empty")]
    redeclared_attrs: Vec<UnivAttr>,
}

#[derive(Serialize)]
struct UnivTypeDef {
    aliased: String,
}

#[derive(Serialize)]
struct UniversalToml {
    entity: BTreeMap<String, UnivEntity>,
    #[serde(rename = "type", skip_serializing_if = "BTreeMap::is_empty")]
    type_aliases: BTreeMap<String, UnivTypeDef>,
}

pub fn run(schemas: &[Schema]) -> Result<(), String> {
    let unified = refgraph::build(schemas);

    // Schemas newest-first: first to declare an entity/type wins.
    let mut ranked: Vec<&Schema> = schemas.iter().collect();
    ranked.sort_by_key(|s| std::cmp::Reverse(schema_rank(&s.source_label)));
    // Chronological (publication-order) view for the per-entity membership
    // list. NOT schema_rank: that is newest-wins *preference* order, which
    // puts ap242e2 (the IS edition) above ap242e3.
    fn chrono_rank(label: &str) -> u8 {
        match label {
            "ap203e1" => 1,
            "ap203e2" => 2,
            "ap214e3" => 3,
            "ap242e1" => 4,
            "ap242e2" => 5,
            "ap242e3" => 6,
            _ => 0,
        }
    }
    let mut chrono: Vec<&Schema> = schemas.iter().collect();
    chrono.sort_by_key(|s| chrono_rank(&s.source_label));

    // complex-part set = the entities any edition lets share a complex record
    // with another, plus their transitive supertypes (which also appear in the
    // complex record).
    let mut combinable: BTreeSet<String> = ranked.iter().flat_map(|s| combinable_in(s)).collect();
    // Corpus-augmented: entities observed as complex-record parts in the corpus
    // (complex_part_count > 0) are genuine combinable leaves, even when the
    // EXPRESS declaration only ONEOF-restricts them (no enclosing AndOr). This
    // recovers real MI combinations the declaration-only rule misses — e.g. the
    // `repositioned_tessellated_geometric_set` complex combines two ONEOF
    // siblings of tessellated_item. The entity_parents guard drops corpus-only
    // measure types (length_measure etc.) that are not schema entities.
    let summary = load_corpus_summary()?;
    for (name, rec) in &summary {
        if rec.complex_part_count > 0 && unified.entity_parents.contains_key(name) {
            combinable.insert(name.clone());
        }
    }
    let mut is_complex_part: BTreeSet<String> = BTreeSet::new();
    let mut stack: Vec<String> = combinable.into_iter().collect();
    while let Some(n) = stack.pop() {
        if !is_complex_part.insert(n.clone()) {
            continue;
        }
        for decl in ranked.iter().filter_map(|s| s.entities.get(&n)) {
            stack.extend(decl.parents.iter().cloned());
        }
    }

    // The declaration written for each entity, and the type table, as the
    // narrowing judge must see them (the same view code generation gets).
    let decls: BTreeMap<&str, &EntitySchema> = unified
        .entity_parents
        .keys()
        .filter_map(|n| {
            ranked
                .iter()
                .find_map(|s| s.entities.get_key_value(n))
                .map(|(k, e)| (k.as_str(), e))
        })
        .collect();
    let (mut select_members, other_aliased) = union_types(&ranked);
    // Declared types every edition does not agree on are widened to cover
    // them all; a SELECT is made up where no declared type does.
    let widening = Judge::new(schemas, &decls, &select_members, &other_aliased).widen(&decls);
    for (n, members) in &widening.synthetic {
        select_members.insert(n.clone(), members.clone());
    }
    let declared_ty = |entity: &str, a: &'_ AttrSpec| -> AttrType {
        widening
            .widened
            .get(&(entity.to_string(), a.name.clone()))
            .cloned()
            .unwrap_or_else(|| a.ty.clone())
    };
    let judge = Judge::new(schemas, &decls, &select_members, &other_aliased);
    let mut report = NarrowingReport {
        widened: widening.widened_report.clone(),
        not_widened: widening.not_widened.clone(),
        optional_elsewhere: widening.optional_elsewhere.clone(),
        aggregate_elsewhere: widening.aggregate_elsewhere.clone(),
        ..NarrowingReport::default()
    };
    // (entity, attribute) → (owner, redeclared type) for every redeclaration
    // written.
    let mut applied: BTreeMap<(String, String), (String, AttrType)> = BTreeMap::new();

    let mut entity: BTreeMap<String, UnivEntity> = BTreeMap::new();
    for name in unified.entity_parents.keys() {
        // own_attrs, parents, and derives all come from the SAME newest-AP decl.
        let decl_schema = ranked.iter().find(|s| s.entities.contains_key(name));
        let decl = decl_schema.and_then(|s| s.entities.get(name));
        let own_attrs: Vec<UnivAttr> = decl
            .map(|e| {
                e.own_attrs
                    .iter()
                    .map(|a| UnivAttr {
                        name: a.name.clone(),
                        ty: ty_repr(&declared_ty(name, a)),
                        owner: None,
                        union_safe: None,
                    })
                    .collect()
            })
            .unwrap_or_default();
        let parents: Vec<String> = decl.map(|e| e.parents.clone()).unwrap_or_default();
        let mut redeclared_attrs: Vec<UnivAttr> = Vec::new();
        if let (Some(ds), Some(e), Some(name)) = (
            decl_schema,
            decl,
            decls.get_key_value(name.as_str()).map(|(k, _)| *k),
        ) {
            for a in &e.redeclared_attrs {
                let owner = redeclaration_owner(ds, a);
                let verdict = judge.judge(name, a);
                let slot = format!("{name}.{}", a.name);
                let ty = if redeclaration_has_signal(&a.ty, &ranked) {
                    if !verdict.union_safe {
                        report.kept_unsafe.push(format!(
                            "{slot} : {} ({})",
                            ty_repr(&a.ty),
                            verdict.reason.unwrap_or_default()
                        ));
                    }
                    Some(a.ty.clone())
                } else if !judge.is_reference(&a.ty) {
                    report
                        .non_reference
                        .push(format!("{slot} : {}", ty_repr(&a.ty)));
                    None
                } else if verdict.union_safe {
                    let base = owner.as_deref().and_then(|o| {
                        decls
                            .get(o)
                            .and_then(|d| d.own_attrs.iter().find(|x| x.name == a.name))
                            .map(|b| declared_ty(o, b))
                    });
                    match base.as_ref().and_then(|b| with_element(b, &a.ty)) {
                        Some(t) => {
                            report.emitted.push(format!(
                                "{slot} : {} -> {}",
                                base.as_ref().map(ty_repr).unwrap_or_default(),
                                ty_repr(&t)
                            ));
                            Some(t)
                        }
                        None => {
                            report.rejected.push(format!(
                                "{slot} : {} (declared type not found or aggregates nest differently)",
                                ty_repr(&a.ty)
                            ));
                            None
                        }
                    }
                } else {
                    report.rejected.push(format!(
                        "{slot} : {} ({})",
                        ty_repr(&a.ty),
                        verdict.reason.unwrap_or_default()
                    ));
                    None
                };
                if let Some(ty) = ty {
                    if let Some(o) = &owner {
                        applied.insert((name.to_string(), a.name.clone()), (o.clone(), ty.clone()));
                    }
                    redeclared_attrs.push(UnivAttr {
                        name: a.name.clone(),
                        ty: ty_repr(&ty),
                        owner,
                        union_safe: Some(verdict.union_safe),
                    });
                }
            }
        }
        let derives: Vec<String> = decl
            .map(|e| {
                e.derived_attrs
                    .iter()
                    .map(|d| match &d.super_qual {
                        Some(s) => format!("{s}.{}", d.name),
                        None => d.name.clone(),
                    })
                    .collect()
            })
            .unwrap_or_default();

        let attr_conflicts: Vec<String> = unified
            .attr_conflicts
            .iter()
            .filter(|((e, _), _)| e == name)
            .map(|((_, a), variants)| format!("{a}: {}", variants.join(" | ")))
            .collect();

        let entity_schemas: Vec<String> = chrono
            .iter()
            .filter(|s| s.entities.contains_key(name))
            .map(|s| s.source_label.clone())
            .collect();

        entity.insert(
            name.clone(),
            UnivEntity {
                parents,
                is_abstract: unified.abstract_entities.contains(name),
                is_complex_part: is_complex_part.contains(name),
                attr_conflicts,
                derives,
                schemas: entity_schemas,
                own_attrs,
                redeclared_attrs,
            },
        );
    }

    // universal = read superset over ALL schemas. SELECT membership is UNIONed
    // across editions (a member legal in any edition must be readable); non-SELECT
    // aliases keep newest-wins (`union_types`, computed above for the judge).
    // (Older editions can carry members a newer edition dropped — e.g.
    // approved_item has product_definition in ap203 but not ap242.)
    let mut type_aliases: BTreeMap<String, UnivTypeDef> = BTreeMap::new();
    for (tn, members) in &select_members {
        type_aliases.insert(
            tn.clone(),
            UnivTypeDef {
                aliased: format!("SELECT({})", members.join(", ")),
            },
        );
    }
    // A name that is SELECT in some schema and a plain alias in another keeps the
    // SELECT union (inserted above); only names that are never SELECT land here.
    for (tn, aliased) in &other_aliased {
        type_aliases.entry(tn.clone()).or_insert(UnivTypeDef {
            aliased: ty_repr(aliased),
        });
    }

    // Where the written schema is narrower than the union of editions: each
    // entity's attributes, under the declared type and every redeclaration
    // applied to it along the entity's supertypes.
    for &name in decls.keys() {
        let chain = universal_ancestors(&decls, name);
        for x in &chain {
            for a in &decls[x].own_attrs {
                let declared = declared_ty(x, a);
                let mut tys: Vec<&AttrType> = vec![&declared];
                for y in &chain {
                    if let Some((o, t)) = applied.get(&(y.to_string(), a.name.clone()))
                        && o == x
                    {
                        tys.push(t);
                    }
                }
                let extra = judge.narrower_than_union(name, &a.name, &tys);
                if !extra.is_empty() {
                    report.narrower_than_union.push(format!(
                        "{name}.{} : also admitted by some edition: {:?}{}",
                        a.name,
                        &extra[..extra.len().min(4)],
                        if extra.len() > 4 { " …" } else { "" }
                    ));
                }
            }
        }
    }
    report.write()?;

    let doc = UniversalToml {
        entity,
        type_aliases,
    };
    let body = toml::to_string_pretty(&doc).map_err(|e| e.to_string())?;
    let header = "# Generated by `universal_export` — schema-faithful codegen input.\n\
                  # DO NOT hand-edit. Faithful schema-union of the source AP schemas + per-entity\n\
                  # `derives` (raw DERIVE targets: \"super.attr\" or \"attr\"); codegen marks\n\
                  # derived/derivable `*` slots from these. Names/own_attrs prefer newest AP;\n\
                  # a declared type editions disagree on is widened to cover them all.\n\
                  # `schemas` = source APs declaring the entity, chronological (membership data).\n\n";
    fs::create_dir_all("inferred").map_err(|e| e.to_string())?;
    fs::write(OUT, format!("{header}{body}")).map_err(|e| e.to_string())?;
    let with_derives = doc
        .entity
        .values()
        .filter(|e| !e.derives.is_empty())
        .count();
    eprintln!(
        "wrote {OUT}: {} entities ({with_derives} with derives), {} type aliases",
        doc.entity.len(),
        doc.type_aliases.len()
    );
    Ok(())
}

#[cfg(test)]
mod tests {
    use std::path::Path;

    use super::*;
    use crate::express::load_all_schemas;

    #[test]
    fn the_subtypes_of_an_entity_that_combines_combine() {
        let schemas = load_all_schemas(Path::new("schemas"));
        let e3 = schemas
            .iter()
            .find(|s| s.source_label == "ap242e3")
            .unwrap();
        let c = combinable_in(e3);
        // feature_definition's ONEOF names round_hole but not barring_hole,
        // which is ANDORed with it; round_hole's ONEOF names basic_round_hole.
        assert!(c.contains("round_hole") && c.contains("barring_hole"));
        assert!(c.contains("basic_round_hole"));
        assert!(!c.contains("application_context"));
    }
}
